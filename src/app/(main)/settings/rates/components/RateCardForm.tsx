function useAutoSelectFirstSlab(activeTab: string, isReadOnly: boolean, slabsLength: number) {
  useEffect(() => {
    if (activeTab === "slabs" && !isReadOnly && slabsLength > 0) {
      const timer = setTimeout(() => {
        const firstInput = document.getElementById(
          "slab-amount-input-0",
        ) as HTMLInputElement | null;
        if (firstInput) {
          firstInput.focus();
          firstInput.select();
        }
      }, 150);
      return () => clearTimeout(timer);
    }
  }, [activeTab, isReadOnly, slabsLength]);
}

function useRateCardInitEffect(
  isCreate: boolean,
  existingRate: unknown,
  reset: (val: unknown) => void,
  setSlabs: (slabs: SlabItem[]) => void,
  setInitialSlabs: (slabs: SlabItem[]) => void,
) {
  useEffect(() => {
    if (isCreate) {
      reset(INITIAL_FORM_STATE);
      setSlabs([]);
      setInitialSlabs([]);
    } else if (existingRate) {
      reset(mapExistingRateToForm(existingRate as Parameters<typeof mapExistingRateToForm>[0]));
      const slabVal = mapExistingRateToSlabs(
        existingRate as Parameters<typeof mapExistingRateToSlabs>[0],
      );
      setSlabs(slabVal);
      setInitialSlabs(slabVal);
    }
  }, [isCreate, existingRate, reset, setSlabs, setInitialSlabs]);
}

function navigateWithConfirm(
  isDirty: boolean,
  askConfirm: ReturnType<typeof useConfirm>["askConfirm"],
  tSettings: (key: string) => string,
  onNavigate: () => void,
) {
  if (isDirty) {
    askConfirm({
      title: tSettings("rates.confirmBackTitle"),
      message: tSettings("rates.confirmBackMessage"),
      confirmLabel: tSettings("rates.btnLeave"),
      cancelLabel: tSettings("rates.btnStay"),
      confirmColor: "warning",
      onConfirm: onNavigate,
    });
  } else {
    onNavigate();
  }
}

function useRateCardPermissions() {
  const { hasPermission: canCreate } = useRequirePermission([Permissions.RATES_CREATE]);
  const { hasPermission: canUpdate } = useRequirePermission([Permissions.RATES_UPDATE]);
  const { hasPermission: canApprove } = useRequirePermission([Permissions.RATES_APPROVE]);

  return { canCreate, canUpdate, canApprove };
}

function useRateCardActiveTab() {
  const pathname = usePathname();
  const router = useRouter();
  const searchParams = useSearchParams();
  const tabParam = searchParams.get("tab");

  const activeTab = useMemo<"info" | "slabs" | "logs">(() => {
    if (tabParam === "slabs" || tabParam === "logs") return tabParam;
    return "info";
  }, [tabParam]);

  const setActiveTab = useCallback(
    (tab: "info" | "slabs" | "logs") => {
      const params = new URLSearchParams(searchParams.toString());
      params.set("tab", tab);
      const qs = params.toString();
      router.push(`${pathname}${qs ? `?${qs}` : ""}`, { scroll: false });
    },
    [router, pathname, searchParams],
  );

  return { activeTab, setActiveTab };
}

function useRateCardQueries(rateCardId: number | null, isCreate: boolean, activeTab: string) {
  const { data: existingRate, isLoading: loadingDetails } = trpc.viewer.rateCards.get.useQuery(
    { id: rateCardId ?? 0 },
    { enabled: !isCreate && rateCardId !== null },
  );

  const { data: logs, isLoading: loadingLogs } = trpc.viewer.rateCards.listLogs.useQuery(
    { id: rateCardId ?? 0 },
    { enabled: !isCreate && rateCardId !== null && activeTab === "logs" },
  );

  return { existingRate, loadingDetails, logs, loadingLogs };
}

export function RateCardForm({ rateCardId }: RateCardFormProps) {
  const isCreate = rateCardId === null;
  const router = useRouter();
  const t = useToast();
  const tSettings = useTranslations("settings");
  const utils = trpc.useUtils();
  const { askConfirm, dialogProps: confirmDialogProps } = useConfirm();

  const { canCreate, canUpdate, canApprove } = useRateCardPermissions();
  const { activeTab, setActiveTab } = useRateCardActiveTab();

  const {
    register,
    control,
    handleSubmit,
    reset,
    watch,
    setValue,
    formState: { errors, isDirty: isInfoDirty },
  } = useForm<typeof INITIAL_FORM_STATE>({
    mode: "onChange",
    resolver: zodResolver(rateCardFormSchema),
    defaultValues: INITIAL_FORM_STATE,
  });

  const formData = watch();
  const [slabs, setSlabs] = useState<SlabItem[]>([]);
  const [initialSlabs, setInitialSlabs] = useState<SlabItem[]>([]);
  const isReadOnly = !isCreate
    ? (formData.status !== "DRAFT" && formData.status !== "REJECTED") || !canUpdate
    : !canCreate;

  const { existingRate, loadingDetails, logs, loadingLogs } = useRateCardQueries(
    rateCardId,
    isCreate,
    activeTab,
  );

  useRateCardInitEffect(isCreate, existingRate, reset, setSlabs, setInitialSlabs);
  useAutoSelectFirstSlab(activeTab, isReadOnly, slabs.length);

  const isSlabsDirty = useMemo(() => checkSlabsDirty(slabs, initialSlabs), [slabs, initialSlabs]);

  const { createMut, updateMut, submitReviewMut, approveMut, rejectMut, importSlabsMut } =
    useRateCardMutations(rateCardId, tSettings);

  const handleSaveInfo = handleSubmit(
    (values) => {
      const payload = prepareSavePayload(values);
      if (isCreate) {
        createMut.mutate(payload);
      } else if (rateCardId) {
        updateMut.mutate({ id: rateCardId, ...payload });
      }
    },
    () => {
      t.toast(tSettings("rates.toastValidationError"), "error");
    },
  );

  const handleSubmitReview = () => {
    if (!rateCardId) return;
    submitReviewMut.mutate({ id: rateCardId });
  };

  const handleApprove = () => {
    if (!rateCardId) return;
    approveMut.mutate({ id: rateCardId });
  };

  const handleReject = () => {
    if (!rateCardId) return;
    rejectMut.mutate({ id: rateCardId });
  };

  const handleSaveSlabs = () => {
    if (!rateCardId) return;
    importSlabsMut.mutate({
      rateCardId,
      slabs,
    });
  };

  const handleBack = useCallback(() => {
    navigateWithConfirm(isInfoDirty || isSlabsDirty, askConfirm, tSettings, () =>
      router.push("/settings/rates"),
    );
  }, [isInfoDirty, isSlabsDirty, askConfirm, router, tSettings]);

  const assignedGroups = useMemo(() => mapAssignedGroups(existingRate), [existingRate]);

  const hasAssignedGroups = formData.type === "CUSTOM" ? assignedGroups.length > 0 : true;

  const [assignGroupModalOpen, setAssignGroupModalOpen] = useState(false);
  const [selectedGroupIds, setSelectedGroupIds] = useState<number[]>([]);
  const [groupSearch, setGroupSearch] = useState("");

  const { data: allGroups } = trpc.viewer.customerGroups.listAll.useQuery(undefined, {
    enabled: formData.type === "CUSTOM" && assignGroupModalOpen,
    staleTime: 5 * 60 * 1000,
  });

  const filteredGroups = useMemo(
    () => filterCustomerGroups(allGroups, groupSearch),
    [allGroups, groupSearch],
  );

  const assignGroupsMut = trpc.viewer.rateCards.assignGroups.useMutation({
    onSuccess: () => {
      t.toast("Đã cập nhật nhóm khách hàng thành công.", "success");
      setAssignGroupModalOpen(false);
      utils.viewer.rateCards.get.invalidate({ id: rateCardId ?? 0 });
      utils.viewer.rateCards.list.invalidate();
    },
    onError: (err) => t.toast(formatErrorMessage(err.message), "error"),
  });

  const handleOpenAssignGroups = useCallback(() => {
    setSelectedGroupIds(assignedGroups.map((g) => g.id));
    setGroupSearch("");
    setAssignGroupModalOpen(true);
  }, [assignedGroups]);

  const totalSlabErrors = useMemo(() => {
    return countSlabErrors(slabs, formData, tSettings);
  }, [slabs, formData, tSettings]);

  const isPending =
    createMut.isPending ||
    updateMut.isPending ||
    submitReviewMut.isPending ||
    approveMut.isPending ||
    rejectMut.isPending ||
    importSlabsMut.isPending ||
    assignGroupsMut.isPending;

  if (loadingDetails) {
    return (
      <div className="flex min-h-[400px] items-center justify-center">
        <Loader2 className="size-8 animate-spin text-muted-foreground" />
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-6 w-full">
      <FormHeader
        isCreate={isCreate}
        code={formData.code}
        status={formData.status}
        activeTab={activeTab}
        isPending={isPending}
        slabsCount={slabs.length}
        totalSlabErrors={totalSlabErrors}
        hasAssignedGroups={hasAssignedGroups}
        tSettings={tSettings}
        onBack={handleBack}
        onSaveInfo={handleSaveInfo}
        onSubmitReview={handleSubmitReview}
        onApprove={handleApprove}
        onReject={handleReject}
        onSaveSlabs={handleSaveSlabs}
        isInfoDirty={isInfoDirty}
        isSlabsDirty={isSlabsDirty}
        isReadOnly={isReadOnly}
        canCreate={canCreate}
        canUpdate={canUpdate}
        canApprove={canApprove}
      />

      <Tabs value={activeTab} onValueChange={(v) => setActiveTab(v as "info" | "slabs" | "logs")}>
        <Card className="rounded-lg border border-border bg-card overflow-hidden">
          {!isCreate && (
            <div className="px-6 pt-6 pb-2 flex items-center">
              <TabsList className="inline-flex h-10 items-center justify-start rounded-lg bg-muted p-1 border border-border">
                <TabsTrigger
                  value="info"
                  className="flex items-center gap-1.5 rounded-md px-4 py-1.5 text-xs md:text-sm font-medium text-muted-foreground transition-all hover:bg-background/50 hover:text-foreground data-[state=active]:bg-background data-[state=active]:text-foreground data-[state=active]:shadow-sm"
                >
                  <Info size={16} className="shrink-0" />
                  <span>{tSettings("rates.tabGeneral")}</span>
                </TabsTrigger>
                <TabsTrigger
                  value="slabs"
                  className="flex items-center gap-1.5 rounded-md px-4 py-1.5 text-xs md:text-sm font-medium text-muted-foreground transition-all hover:bg-background/50 hover:text-foreground data-[state=active]:bg-background data-[state=active]:text-foreground data-[state=active]:shadow-sm"
                >
                  <Scale size={16} className="shrink-0" />
                  <span>{tSettings("rates.tabSlabs")}</span>
                  {totalSlabErrors > 0 && (
                    <Badge
                      variant="destructive"
                      className="ml-1 px-1.5 py-0 text-[10px] h-4 leading-none font-semibold"
                    >
                      {totalSlabErrors}
                    </Badge>
                  )}
                </TabsTrigger>
                <TabsTrigger
                  value="logs"
                  className="flex items-center gap-1.5 rounded-md px-4 py-1.5 text-xs md:text-sm font-medium text-muted-foreground transition-all hover:bg-background/50 hover:text-foreground data-[state=active]:bg-background data-[state=active]:text-foreground data-[state=active]:shadow-sm"
                >
                  <History size={16} className="shrink-0" />
                  <span>{tSettings("rates.tabLogs")}</span>
                </TabsTrigger>
              </TabsList>
            </div>
          )}

          <CardContent className="px-6 pb-6 pt-6">
            <TabsContent value="info" className="mt-0 outline-none">
              <GeneralInfoTab
                control={control}
                register={register}
                errors={errors}
                watch={watch}
                setValue={setValue}
                isCreate={isCreate}
                tSettings={tSettings}
                status={formData.status}
                rateCardId={rateCardId}
                assignedGroups={assignedGroups}
                onOpenAssignGroups={handleOpenAssignGroups}
              />
            </TabsContent>

            {!isCreate && (
              <>
                <TabsContent value="slabs" className="mt-0 outline-none">
                  <SlabsTab
                    formData={formData}
                    slabs={slabs}
                    setSlabs={setSlabs}
                    tSettings={tSettings}
                    isReadOnly={isReadOnly}
                    askConfirm={askConfirm}
                  />
                </TabsContent>

                <TabsContent value="logs" className="mt-0 outline-none">
                  <LogsTab logs={logs} loadingLogs={loadingLogs} tSettings={tSettings} />
                </TabsContent>
              </>
            )}
          </CardContent>
        </Card>
      </Tabs>

      {/* Assign Groups Modal */}
      {assignGroupModalOpen && (
        <AssignGroupsModal
          open={assignGroupModalOpen}
          onOpenChange={setAssignGroupModalOpen}
          code={formData.code}
          groupSearch={groupSearch}
          onGroupSearchChange={setGroupSearch}
          filteredGroups={filteredGroups}
          selectedGroupIds={selectedGroupIds}
          onToggleGroup={(id) => {
            setSelectedGroupIds((prev) =>
              prev.includes(id) ? prev.filter((groupId) => groupId !== id) : [...prev, id],
            );
          }}
          isPending={assignGroupsMut.isPending || !rateCardId}
          onSave={() => {
            if (rateCardId) {
              assignGroupsMut.mutate({
                id: rateCardId,
                customerGroupIds: selectedGroupIds,
              });
            }
          }}
        />
      )}

      <ConfirmDialog {...confirmDialogProps} />
    </div>
  );
}
