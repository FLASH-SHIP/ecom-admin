function mapExistingRateToSlabs(existingRate: {
  minWeight?: unknown;
  maxWeight?: unknown;
  weightStep?: unknown;
  items?: {
    startWeight?: unknown;
    endWeight?: unknown;
    rateType?: string;
    amount?: unknown;
  }[];
}): SlabItem[] {
  const minWeight = Number(existingRate.minWeight ?? 0);
  const maxWeight = Number(existingRate.maxWeight ?? 0);
  const weightStep = Number(existingRate.weightStep ?? 0.5);

  if (existingRate.items && existingRate.items.length > 0) {
    return existingRate.items.map((it) => {
      const sw = Number(it.startWeight ?? 0);
      const ew = Number(it.endWeight ?? 0);
      const isAutoGenerated = sw >= minWeight && ew <= maxWeight;

      return {
        startWeight: sw,
        endWeight: ew,
        rateType: (it.rateType ?? "STEP_FIXED") as SlabItem["rateType"],
        amount: Number(it.amount ?? 0),
        isAutoGenerated,
        keyId: `${sw}-${ew}-${Math.random()}`,
      };
    });
  }

  return generateDefaultSlabs(minWeight, maxWeight, weightStep);
}

