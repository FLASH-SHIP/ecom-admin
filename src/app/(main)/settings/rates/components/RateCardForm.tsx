interface EffectiveDateFieldsProps {
  control: Control<typeof INITIAL_FORM_STATE>;
  errors: FieldErrors<typeof INITIAL_FORM_STATE>;
  type: RateCardType;
  startDateStr?: string;
  isReadOnly: boolean;
  tSettings: (key: string, values?: Record<string, string | number | Date>) => string;
  getErrorMessage: (field: keyof typeof INITIAL_FORM_STATE) => string | undefined;
}

function EffectiveDateFields({
  control,
  errors,
  type,
  startDateStr,
  isReadOnly,
  tSettings,
  getErrorMessage,
}: EffectiveDateFieldsProps) {
  const isPastDate = (date: Date) => {
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    return date < today;
  };

  const isInvalidEndDate = (date: Date) => {
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    if (date < today) return true;
    if (startDateStr) {
      const start = new Date(startDateStr);
      start.setHours(0, 0, 0, 0);
      if (date < start) return true;
    }
    return false;
  };

  return (
    <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
      <div className="flex flex-col gap-1.5">
        <Label className="font-semibold text-xs">
          {tSettings("rates.lblStartDate")} <span className="text-destructive">*</span>
        </Label>
        <Controller
          control={control}
          name="startDate"
          render={({ field }) => (
            <DatePicker
              value={field.value ?? ""}
              onChange={field.onChange}
              placeholder="dd/mm/yyyy"
              disabled={isReadOnly}
              disabledDays={isPastDate}
            />
          )}
        />
        {errors.startDate && (
          <span className="text-[11px] text-destructive font-medium mt-0.5">
            {getErrorMessage("startDate")}
          </span>
        )}
      </div>
      <div className="flex flex-col gap-1.5">
        <Label className="font-semibold text-xs">{tSettings("rates.lblEndDate")}</Label>
        {type === "DEFAULT" ? (
          <div className="h-9 px-3 border border-input rounded-md bg-muted/40 text-xs text-muted-foreground flex items-center">
            {tSettings("rates.defaultEndDateNote")}
          </div>
        ) : (
          <Controller
            control={control}
            name="endDate"
            render={({ field }) => (
              <DatePicker
                value={field.value ?? ""}
                onChange={field.onChange}
                placeholder="dd/mm/yyyy"
                disabled={isReadOnly}
                disabledDays={isInvalidEndDate}
              />
            )}
          />
        )}
        {errors.endDate && (
          <span className="text-[11px] text-destructive font-medium mt-0.5">
            {getErrorMessage("endDate")}
          </span>
        )}
      </div>
    </div>
  );
}

