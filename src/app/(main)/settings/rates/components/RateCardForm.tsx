type SlabItem = {
  startWeight: number;
  endWeight: number;
  rateType: "STEP_FIXED" | "RANGE_FIXED" | "RANGE_PER_KG";
  amount: number;
  isAutoGenerated?: boolean;
  keyId: string;
};

function generateDefaultSlabs(
  minWeight: number,
  maxWeight: number,
  weightStep: number,
  rateType: SlabItem["rateType"] = "STEP_FIXED",
): SlabItem[] {
  if (minWeight == null || maxWeight == null || weightStep == null) return [];
  if (minWeight < 0 || maxWeight <= minWeight || weightStep <= 0) return [];
  const items: SlabItem[] = [];
  let curr = Number(Number(minWeight).toFixed(3));
  const maxW = Number(Number(maxWeight).toFixed(3));
  const step = Number(Number(weightStep).toFixed(3));

  while (curr < maxW) {
    let next = Number((curr + step).toFixed(3));
    if (next > maxW) next = maxW;
    items.push({
      startWeight: curr,
      endWeight: next,
      rateType,
      amount: 0,
      isAutoGenerated: true,
      keyId: `${curr}-${next}-${Math.random()}`,
    });
    curr = next;
  }
  return items;
}

